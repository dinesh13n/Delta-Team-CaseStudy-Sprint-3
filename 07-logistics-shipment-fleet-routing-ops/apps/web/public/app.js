// Read-only operations view. Every API value is written with textContent only (values may be untrusted).
"use strict";
const $ = (id) => document.getElementById(id);
const state = { token: "", offset: 0, limit: 10, total: 0, current: null, summary: null };

function showError(msg) { const e = $("error"); e.hidden = !msg; e.textContent = msg || ""; }

async function api(path, opts = {}) {
  const headers = { Authorization: "Bearer " + state.token, ...(opts.body ? { "Content-Type": "application/json" } : {}) };
  const res = await fetch(path, { ...opts, headers });
  const cid = res.headers.get("X-Correlation-ID");
  if (cid) $("cid").textContent = "correlation id: " + cid;
  if (!res.ok) {
    let detail = res.status + " " + res.statusText;
    try { const p = await res.json(); detail = res.status + " " + (p.title || "") + (p.detail ? ": " + p.detail : ""); } catch (_) { /* not json */ }
    throw new Error(detail);
  }
  return res.json();
}

function roleOf(token) {
  try { return JSON.parse(atob(token.split(".")[1].replace(/-/g, "+").replace(/_/g, "/"))).role || "unknown"; } catch (_) { return "unknown"; }
}

function cell(tr, text) { const td = document.createElement("td"); td.textContent = text == null ? "" : String(text); tr.appendChild(td); }

async function loadList() {
  showError("");
  const q = new URLSearchParams({ limit: state.limit, offset: state.offset });
  if ($("status").value) q.set("status", $("status").value);
  const data = await api("/shipments?" + q);
  state.total = data.total;
  const body = $("list").tBodies[0]; body.replaceChildren();
  for (const r of data.items) {
    const tr = document.createElement("tr"); tr.tabIndex = 0; tr.dataset.id = r.shipment_id;
    cell(tr, r.shipment_id); cell(tr, r.status); cell(tr, r.service_tier); cell(tr, r.promised_at);
    tr.addEventListener("click", () => openRecord(r.shipment_id));
    tr.addEventListener("keydown", (e) => { if (e.key === "Enter") openRecord(r.shipment_id); });
    body.appendChild(tr);
  }
  $("page").textContent = `${Math.min(state.offset + 1, state.total)}-${Math.min(state.offset + state.limit, state.total)} of ${state.total}`;
  $("whoami").textContent = "role: " + roleOf(state.token);
}

async function openRecord(id) {
  showError(""); state.current = id; state.summary = null;
  $("suggestion").replaceChildren(); $("decision").textContent = ""; $("approve").disabled = $("reject").disabled = true;
  const [rec, ev] = await Promise.all([api("/records/" + encodeURIComponent(id)), api("/shipments/" + encodeURIComponent(id) + "/events")]);
  const dl = $("record"); dl.replaceChildren();
  for (const [k, v] of Object.entries(rec)) {
    const dt = document.createElement("dt"); dt.textContent = k; const dd = document.createElement("dd"); dd.textContent = v == null ? "" : String(v);
    dl.append(dt, dd);
  }
  const ol = $("events"); ol.replaceChildren();
  for (const e of ev) { const li = document.createElement("li"); li.textContent = `${e.event_time} ${e.event_type} (${e.source_system})`; ol.appendChild(li); }
  $("summarize").disabled = false;
}

async function summarize() {
  showError("");
  const s = await api("/ai/summarize/" + encodeURIComponent(state.current), { method: "POST" });
  state.summary = s;
  const box = $("suggestion"); box.replaceChildren();
  const d = document.createElement("div"); d.className = "suggestion";
  const lines = s.abstained
    ? ["Abstained: " + s.abstain_reason]
    : ["Summary: " + s.summary, "Recommendation: " + s.recommendation];
  lines.push(`Generated by: ${s.generated_by} (${s.model} ${s.model_version}); guardrail: ${s.guardrail_status}; sources: ${s.source_count}; ` +
             `tokens (${s.token_source}): ${s.token_estimate}`, "Suggestion only. A person must decide.");
  for (const t of lines) { const p = document.createElement("p"); p.textContent = t; d.appendChild(p); }
  box.appendChild(d);
  $("approve").disabled = $("reject").disabled = false;
}

async function decide(decision) {
  showError("");
  const r = await api("/ai/summaries/" + encodeURIComponent(state.summary.summary_id) + "/decision",
    { method: "POST", body: JSON.stringify({ decision, reason: $("reason").value || null }) });
  $("decision").textContent = `Recorded: ${r.decision} by ${r.decided_by} at ${r.decided_at} (approval ${r.approval_id})`;
  $("approve").disabled = $("reject").disabled = true;
}

const guard = (fn) => async (...a) => { try { await fn(...a); } catch (e) { showError(e.message); } };
$("auth").addEventListener("submit", guard(async (ev) => { ev.preventDefault(); state.token = $("token").value.trim(); state.offset = 0; await loadList(); }));
$("status").addEventListener("change", guard(async () => { state.offset = 0; await loadList(); }));
$("prev").addEventListener("click", guard(async () => { state.offset = Math.max(0, state.offset - state.limit); await loadList(); }));
$("next").addEventListener("click", guard(async () => { if (state.offset + state.limit < state.total) { state.offset += state.limit; await loadList(); } }));
$("summarize").addEventListener("click", guard(summarize));
$("approve").addEventListener("click", guard(() => decide("approve")));
$("reject").addEventListener("click", guard(() => decide("reject")));
